export const fallback =
  'Для такой подсказки мне недостаточно данных. Пришли ' +
  'обезличенный текст сообщения или уточни, что именно в нём непонятно.';

export function resolveReply(decision) {
  if (decision?.category === 'OUT_OF_SCOPE') {
    return 'Я помогаю только с распознаванием фишинговых сообщений ' +
      'и заданиями этого курса.';
  }

  if (decision?.category === 'READY_ANSWER') {
    return hints.practice;
  }

  if (decision?.category === 'INSUFFICIENT') {
    return fallback;
  }

  if (
    decision?.category === 'HINT' &&
    Object.hasOwn(hints, decision.hint)
  ) {
    return hints[decision.hint];
  }

  return fallback;
}

