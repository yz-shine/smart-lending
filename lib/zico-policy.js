// Короткие вопросы об определении получают проверенное объяснение напрямую.
// Сложные и смешанные запросы по-прежнему разбирает Gemini.
export function directReply(text) {
  const raw = text.toLowerCase().replace(/ё/g, 'е');
  const unclear = /не (?:поняла|понял|понятн\p{L}*)|непонятн\p{L}*|объясни подробн\p{L}*|подробно объясни/u;
  const wantsAnswer = /(?:какую|какой|назови|скажи)[^.?!]{0,30}(?:букву|вариант)|готов\p{L}* ответ|просто скажи/u;
  if (unclear.test(raw) && !wantsAnswer.test(raw)) return hints.clarify;
  const question = text.toLowerCase().replace(/ё/g, 'е')
    .replace(/[?!.,«»"']/g, ' ').replace(/\s+/g, ' ').trim();
  if (question.length > 150) return null;
  const definitions = [
    /^(?:скажи |расскажи |объясни )?(?:пожалуйста )?что (?:такое|значит|означает) фишинг(?: простыми словами)?(?: пожалуйста)?$/,
    /^(?:объясни|опиши|расскажи)(?: мне)?(?: пожалуйста)?(?: про| о том что такое)? фишинг(?: простыми словами| кратко)?(?: пожалуйста)?$/,
    /^фишинг (?:это что|что это)(?: такое)?$/,
    /^(?:дай|напиши) (?:краткое )?определение фишинга$/
  ];
  return definitions.some(pattern => pattern.test(question)) ? hints.definition : null;
}

export function parseDecision(answer) {
  let decision;
  try { decision = JSON.parse(answer); } catch { return null; }
  if (!decision || typeof decision !== 'object' || Array.isArray(decision)) return null;
  if (['OUT_OF_SCOPE', 'READY_ANSWER', 'INSUFFICIENT'].includes(decision.category)) return decision;
  if (decision.category === 'OPEN' && typeof decision.text === 'string') return decision;
  if (decision.category === 'HINT' && typeof decision.hint === 'string' && Object.hasOwn(hints, decision.hint)) return decision;
  return null;
}

const norm = text => String(text).toLowerCase().replace(/ё/g, 'е')
  .replace(/[^\p{L}\p{N}\s]/gu, ' ').replace(/\s+/g, ' ').trim();

// Формулировки верных вариантов из ситуаций и итоговых вопросов.
function correctOptionTexts() {
  const texts = [...addressActs, ...macroActs].filter(action => action.ok).map(action => action.t);
  for (const module of modules) {
    for (const item of module.cases) {
      for (const [id, text] of item.options || []) if (id === item.correct) texts.push(text);
    }
    const {questions} = getFinalCheck(module.id);
    for (const question of questions) question.key.forEach(i => texts.push(question.options[i]));
  }
  return texts;
}

// Свободный ответ допускается, если он короткий и не раскрывает решение задания.
export function safeOpenText(text) {
  if (typeof text !== 'string') return false;
  const value = text.trim();
  if (value.length < 20 || value.length > 700) return false;
  if (/https?:|www\.|\w+\.(?:com|org|net|uz|example)\b/i.test(value)) return false;
  if (/\d{4,}/.test(value)) return false;
  const reveals = /нужно выбрать вариант|(?:правильн|верн)\p{L}*\s+(?:ответ|вариант)|(?:ответ|вариант)\s*[:\-—]?\s*[«"]?[а-гa-d][)».\s]*$|выбери(?:те)?\s+(?:вариант\s+)?[а-г]\b/iu;
  if (reveals.test(value)) return false;
  const reply = ' ' + norm(value) + ' ';
  for (const option of correctOptionTexts()) {
    const words = norm(option).split(' ');
    for (let i = 0; i + 6 <= words.length; i++) {
      if (reply.includes(' ' + words.slice(i, i + 6).join(' ') + ' ')) return false;
    }
  }
  return true;
}
